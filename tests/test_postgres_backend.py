def _columns_sqlite(path: str) -> dict[str, list[str]]:
    connection = sqlite3.connect(path)
    try:
        tables = [
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            )
        ]
        return {
            table: [row[1] for row in connection.execute(f"PRAGMA table_info({table})")]
            for table in sorted(tables)
        }
    finally:
        connection.close()


def _columns_postgres(url: str) -> dict[str, list[str]]:
    with psycopg.connect(url) as connection:
        rows = connection.execute(
            """
            SELECT table_name, column_name FROM information_schema.columns
            WHERE table_schema = current_schema()
            ORDER BY table_name, ordinal_position
            """
        ).fetchall()
    columns: dict[str, list[str]] = {}
    for table, column in rows:
        columns.setdefault(table, []).append(column)
    return columns


@pytest.mark.postgres_backend
def test_schema_on_the_server_has_exactly_the_sqlite_tables_and_columns(postgres_url, tmp_path):
    """Drift gate: SCHEMA is the single source, so a column added for SQLite lands here too."""

    sqlite_path = str(tmp_path / "parity.db")
    for database in (Database(sqlite_path), Database(postgres_url)):
        database.initialize()
        with database.connect() as connection:
            connection.executescript(RECEIPT_SCHEMA)

    postgres = _columns_postgres(postgres_url)
    assert Database(postgres_url).dialect == "postgresql"
    assert "audit_events" in postgres and "resource_leases" in postgres
    assert postgres == _columns_sqlite(sqlite_path)


