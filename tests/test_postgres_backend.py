def _counter(database: Database) -> None:
    with database.connect() as connection:
        connection.execute(
            "CREATE TABLE IF NOT EXISTS counter (id INTEGER PRIMARY KEY, value INTEGER)"
        )
        connection.execute(
            "INSERT INTO counter (id, value) VALUES (1, 0) ON CONFLICT (id) DO NOTHING"
        )


def _increment(database: Database) -> str:
    try:
        with database.connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            value = connection.execute("SELECT value FROM counter WHERE id = 1").fetchone()[0]
            time.sleep(0.002)  # widen the read-modify-write window
            connection.execute("UPDATE counter SET value = ? WHERE id = 1", (value + 1,))
    except StorageBusyError as error:
        return error.code
    return "ok"


class _LockInsideSnapshot(PostgresConnection):
    """The tempting wrong order: serializable transaction first, xact lock as its first statement."""

    def begin_write(self) -> None:
        if self._write:
            return
        self._raw.autocommit = False
        self._raw.isolation_level = psycopg.IsolationLevel.SERIALIZABLE
        self._raw.execute("SELECT pg_advisory_xact_lock(%s)", (self._lock_key,))
        self._write = True


class _NoLockReadCommitted(PostgresConnection):
    """Known-broken control: what the backend would be without its lock or its isolation level."""

    def begin_write(self) -> None:
        if self._write:
            return
        self._raw.autocommit = False
        self._raw.isolation_level = psycopg.IsolationLevel.READ_COMMITTED
        self._write = True


def _race_counter(
    url: str, connection_class: type[PostgresConnection] | None
) -> tuple[int, dict[str, int]]:
    setup = Database(url)
    setup.initialize()
    _counter(setup)
    threads, per_thread = 8, 15
    databases = []
    for _ in range(threads):
        database = Database(url)
        if connection_class is not None:
            database._backend.connection_class = connection_class
        databases.append(database)
    start = threading.Barrier(threads)

    def run(database: Database) -> list[str]:
        start.wait(timeout=30)
        return [_increment(database) for _ in range(per_thread)]

    with ThreadPoolExecutor(max_workers=threads) as pool:
        outcomes = [code for batch in pool.map(run, databases) for code in batch]
    tally: dict[str, int] = {}
    for code in outcomes:
        tally[code] = tally.get(code, 0) + 1
    final = setup.one("SELECT value FROM counter WHERE id = 1")[0]
    return final, tally


@pytest.mark.postgres_backend
def test_lock_before_snapshot_serialises_writers_with_no_aborts_and_no_lost_updates(postgres_url):
    final, tally = _race_counter(postgres_url, None)
    assert tally == {"ok": 120}, tally
    assert final == 120


@pytest.mark.postgres_backend
def test_control_lock_inside_snapshot_is_correct_but_aborts_under_contention(postgres_url):
    final, tally = _race_counter(postgres_url, _LockInsideSnapshot)
    assert tally.get("storage_serialization_conflict", 0) > 0, tally
    assert final == tally["ok"], "SERIALIZABLE must still refuse every lost update"


@pytest.mark.postgres_backend
def test_control_without_lock_or_serializable_loses_updates(postgres_url):
    final, tally = _race_counter(postgres_url, _NoLockReadCommitted)
    assert tally == {"ok": 120}, tally
    assert final < 120, "the counter cannot detect a lost update, so the green tests prove nothing"


@pytest.mark.postgres_backend
def test_lock_wait_past_its_timeout_is_a_503_that_names_no_host(postgres_url):
    app = create_app(
        Settings(
            database_path=postgres_url,
            admin_key="test-admin",
            signing_key="test-signing-key-with-enough-entropy",
            issuer="test-control-plane",
        )
    )
    backend = app.state.database._backend
    backend.lock_timeout_seconds = 0.3
    holder = psycopg.connect(postgres_url, autocommit=True)
    try:
        holder.execute("SELECT pg_advisory_lock(%s)", (backend._lock_key,))
        with TestClient(app) as client:
            response = client.post(
                "/v1/agents",
                headers={"X-Control-Plane-Key": "test-admin"},
                json={"name": "blocked", "owner": "ops@example.com", "role": "worker"},
            )
    finally:
        holder.close()
    assert response.status_code == 503, response.text
    assert response.headers["retry-after"] == "1"
    assert response.json() == {
        "error": "storage_lock_timeout",
        "message": "storage is busy; retry the request",
    }
    assert "127.0.0.1" not in response.text


@pytest.mark.postgres_backend
def test_a_holder_that_goes_silent_mid_transaction_is_evicted_and_cannot_commit(postgres_url):
    """A client host that partitions while holding the write lock must not wedge every host.

    The server's idle timeout ends the silent session, which rolls its transaction back and
    releases the session lock. The survivor then gets through, and the evicted holder's
    eventual commit fails instead of landing late.
    """

    Database(postgres_url).initialize()
    silent = Database(postgres_url)
    silent._backend.idle_timeout_seconds = 1.0
    survivor = Database(postgres_url)
    survivor._backend.lock_timeout_seconds = 10.0

    context = silent.connect()
    connection = context.__enter__()
    connection.execute("BEGIN IMMEDIATE")
    connection.execute(
        "UPDATE meta SET value = 'from-the-partitioned-host' WHERE key = 'written_by'"
    )

    started = time.monotonic()
    survivor.execute("UPDATE meta SET value = 'survivor' WHERE key = 'written_by'")
    waited = time.monotonic() - started

    with pytest.raises(StorageBusyError):
        context.__exit__(None, None, None)
    assert 0.5 < waited < 8, f"survivor waited {waited:.2f}s"
    assert survivor.one("SELECT value FROM meta WHERE key = 'written_by'")[0] == "survivor"
