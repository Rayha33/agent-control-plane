"""Board #568: the PostgreSQL backend keeps SQLite's one-writer-at-a-time property across hosts.

The service's invariants (one winner per claim, monotonic fencing tokens, an unforked audit
chain) are written against SQLite's `BEGIN IMMEDIATE`. These tests pin what the PostgreSQL
backend substitutes for it, and each mechanism is paired with a control that shows the
measurement can fail:

- the read-modify-write counter loses updates with NO lock under READ COMMITTED, so its
  "no lost update" assertion is not vacuous;
- taking the lock INSIDE the serializable snapshot is still correct but aborts under
  contention, so "zero aborts" measures the lock order rather than luck.

Tests that need a server use the ``postgres_url`` fixture (ACP_TEST_POSTGRES_URL) and skip
without one; the translation tests always run.
"""

